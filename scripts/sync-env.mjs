#!/usr/bin/env node
/**
 * Consolidate local QA configurations from one root .env.
 * Never copy a production DATABASE_URL or production Storage key into destructive QA environments.
 * Root .env values take precedence for explicit QA keys; existing local secrets are preserved otherwise.
 * No network I/O, no npm dependencies, and no credentials in console output.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync, chmodSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const TARGETS = [
  'vdr-qa-starter/.env',
  'virtual-data-room-main/apps/api/test/.env.test',
  '.env.k6', '.env.browser',
  'vdr-qa-starter/.env.storage',
  'virtual-data-room-main/apps/web/.env.local',
];
function parseEnv(content) {
  const obj = {};
  for (const [index, line] of content.split(/\r?\n/).entries()) {
    if (!line.trim() || /^\s*#/.test(line)) continue;
    const match = line.match(/^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/);
    if (!match) continue; // Ignore comments and unrelated shell commands; never execute them.
    let v = match[2].trim();
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) {
      const quote=v[0]; v=v.slice(1,-1);
      if (quote==='"') v=v.replace(/\\n/g,'\n').replace(/\\r/g,'\r').replace(/\\"/g,'"');
    } else v=v.replace(/\s+#.*$/, '').trim();
    if (v.includes('\0')) throw new Error(`Invalid NUL byte in dotenv value ${match[1]} on line ${index + 1}`);
    obj[match[1]] = v;
  }
  return obj;
}
const read = rel => existsSync(join(ROOT,rel)) ? parseEnv(readFileSync(join(ROOT,rel),'utf8')) : {};
const root = read('.env');
const current = Object.fromEntries(TARGETS.map(x=>[x,read(x)]));
const choose = (obj, keys, fallback = '') => {
  for (const key of keys) if (root[key] !== undefined && root[key] !== '') return root[key];
  for (const key of keys) if (obj[key] !== undefined && obj[key] !== '') return obj[key];
  return fallback;
};
const raw = (name, existing = {}, fallback = '') => choose(existing, [name], fallback);
const localPg = value => {
  let u; try {u = new URL(value);} catch {return false;}
  return ['postgresql:','postgres:'].includes(u.protocol) && ['localhost','127.0.0.1','[::1]'].includes(u.hostname)
    && decodeURIComponent(u.pathname.slice(1)) === 'vdr_qa_test' && Boolean(u.port);
};
const safeOrigin = (value, allowRemote = false) => {
  let u; try {u=new URL(value);} catch {throw new Error('Invalid QA URL in root .env (expected bare http(s) origin)');}
  if (u.username || u.password || u.pathname!=='/' || u.search || u.hash || !['http:','https:'].includes(u.protocol)) throw new Error('QA URL must be a bare origin without tokens/paths');
  const loop=['localhost','127.0.0.1','[::1]'].includes(u.hostname);
  if (!loop && (u.protocol!=='https:' || !allowRemote)) throw new Error('QA URL must be local unless explicitly approved for read-only tests');
  return u.origin;
};
const dotenvValue = value => {
  if (/[\r\n\0]/.test(value)) throw new Error('Multiline QA environment values are not supported');
  return JSON.stringify(value); // standard dotenv double-quoted form
};
const bashValue = value => {
  if (/[\r\n\0]/.test(value)) throw new Error('Multiline QA environment values are not supported');
  return "'" + value.replaceAll("'", "'\\''") + "'"; // compatible with source test/.env.test
};
const makeValue = value => {
  if (!/^[A-Za-z0-9_./:@=-]+$/.test(value)) throw new Error('Unsafe Makefile environment value; use a simpler local QA value');
  return value;
};
function write(rel, obj, format='dotenv') {
  const file = join(ROOT,rel);
  mkdirSync(dirname(file),{recursive:true});
  const encode = format==='shell' ? bashValue : format==='make' ? makeValue : dotenvValue;
  const content = `# Generated by make env-sync from root .env; mode 0600. Edit the root .env instead.\n`+
    Object.entries(obj).map(([key,value])=>`${key}=${encode(String(value))}`).join('\n')+'\n';
  // Do not write partial output if validation fails.
  writeFileSync(file, content, {encoding:'utf8', mode:0o600});
  chmodSync(file,0o600);
}
function run() {
  const ui = current['vdr-qa-starter/.env'];
  const api = current['virtual-data-room-main/apps/api/test/.env.test'];
  const k6 = current['.env.k6'];
  const browser = current['.env.browser'];
  const storage = current['vdr-qa-starter/.env.storage'];
  const web = current['virtual-data-room-main/apps/web/.env.local'];

  const qaPort=choose({},['QA_API_PORT'],'3100');
  if (!/^\d{2,5}$/.test(qaPort) || +qaPort>65535) throw new Error('QA_API_PORT must be a valid TCP port');
  const localApi=`http://127.0.0.1:${qaPort}`;
  const webUrl=choose(ui,['QA_WEB_BASE_URL','WEB_BASE_URL'],'https://virtual-data-room-ten.vercel.app');
  const apiUrl=choose(ui,['QA_API_BASE_URL','API_BASE_URL','VITE_API_URL'],'https://virtual-data-room-production.up.railway.app');
  safeOrigin(webUrl, true); safeOrigin(apiUrl, true);
  const ownerEmail=choose(ui,['QA_OWNER_EMAIL','OWNER_EMAIL','TEST_OWNER_EMAIL','TEST_ACCOUNT_EMAIL','E2E_OWNER_EMAIL']);
  const ownerPassword=choose(ui,['QA_OWNER_PASSWORD','OWNER_PASSWORD','TEST_OWNER_PASSWORD','TEST_ACCOUNT_PASSWORD','E2E_OWNER_PASSWORD']);
  const uiConfig={
    WEB_BASE_URL:webUrl, API_BASE_URL:apiUrl, OWNER_EMAIL:ownerEmail, OWNER_PASSWORD:ownerPassword,
    VIEWER_EMAIL:choose(ui,['QA_VIEWER_EMAIL','VIEWER_EMAIL','TEST_VIEWER_EMAIL']),
    VIEWER_PASSWORD:choose(ui,['QA_VIEWER_PASSWORD','VIEWER_PASSWORD','TEST_VIEWER_PASSWORD']),
    QA_ROOM_NAME:choose(ui,['QA_ROOM_NAME'],'My Data Room'),
    QA_ROOM_ID:raw('QA_ROOM_ID',ui), QA_FILE_NAME:raw('QA_FILE_NAME',ui,'Overview.pdf'),
    QA_FOLDER_NAME:raw('QA_FOLDER_NAME',ui),
    QA_READONLY_ALLOW_REMOTE:raw('QA_READONLY_ALLOW_REMOTE',ui,'0'),
    QA_API_APPROVED_ORIGIN:raw('QA_API_APPROVED_ORIGIN',ui),
    QA_UI_AUTO_DISCOVER:raw('QA_UI_AUTO_DISCOVER',ui,'1'),
    LHCI_WEB_BASE_URL:choose(ui,['LHCI_WEB_BASE_URL'],'http://127.0.0.1:4173'),
    LHCI_ALLOW_REMOTE:raw('LHCI_ALLOW_REMOTE',ui,'0'),
    LHCI_RUNS:raw('LHCI_RUNS',ui,'3'),
    LHCI_ROOM_ID:raw('LHCI_ROOM_ID',ui),
  };
  if (uiConfig.QA_READONLY_ALLOW_REMOTE!=='1' && uiConfig.QA_READONLY_ALLOW_REMOTE!=='0') throw new Error('QA_READONLY_ALLOW_REMOTE must be 0 or 1');
  safeOrigin(uiConfig.LHCI_WEB_BASE_URL,uiConfig.LHCI_ALLOW_REMOTE==='1');
  if (!['0','1'].includes(uiConfig.LHCI_ALLOW_REMOTE)) throw new Error('LHCI_ALLOW_REMOTE must be 0 or 1');
  if (!/^[1-5]$/.test(uiConfig.LHCI_RUNS)) throw new Error('LHCI_RUNS must be integer 1 to 5');
  if (uiConfig.QA_API_APPROVED_ORIGIN) safeOrigin(uiConfig.QA_API_APPROVED_ORIGIN,true);
  // Never inherit root DATABASE_URL/DIRECT_URL/JWT_SECRET/SUPABASE_SERVICE_ROLE_KEY implicitly.
  const defaultPg = 'postgresql://qa:qa_local_only@127.0.0.1:54329/vdr_qa_test';
  const pg=choose({},['QA_DATABASE_URL','QA_TEST_DATABASE_URL'],localPg(api.DATABASE_URL || '') ? api.DATABASE_URL : defaultPg);
  const direct=choose({},['QA_DIRECT_URL','QA_TEST_DIRECT_URL'],localPg(api.DIRECT_URL || '') ? api.DIRECT_URL : pg);
  if (!localPg(pg) || !localPg(direct)) throw new Error('Refusing non-local QA PostgreSQL. QA_DATABASE_URL and QA_DIRECT_URL must target local vdr_qa_test');
  if (new URL(pg).origin!==new URL(direct).origin || new URL(pg).pathname!==new URL(direct).pathname) throw new Error('QA DB URLs must refer to the same local database');
  const ack=raw('QA_INTEGRATION_ACK',api,'I_OWN_THIS_LOCAL_DB');
  if (ack!=='I_OWN_THIS_LOCAL_DB') throw new Error('Invalid QA_INTEGRATION_ACK');
  const apiConfig={
    DATABASE_URL:pg, DIRECT_URL:direct, QA_INTEGRATION_ACK:ack,
    JWT_SECRET:choose({},['QA_JWT_SECRET'],api.JWT_SECRET || 'qa_only_do_not_reuse_in_production_really_random_value'),
    SUPABASE_URL:choose({},['QA_TEST_SUPABASE_URL','QA_SUPABASE_URL'],api.SUPABASE_URL || 'https://storage.invalid'),
    SUPABASE_SERVICE_ROLE_KEY:choose({},['QA_TEST_SUPABASE_SERVICE_ROLE_KEY','QA_SUPABASE_SERVICE_ROLE_KEY'],api.SUPABASE_SERVICE_ROLE_KEY || 'qa-test-placeholder'),
    SUPABASE_BUCKET:choose({},['QA_TEST_SUPABASE_BUCKET','QA_SUPABASE_BUCKET'],api.SUPABASE_BUCKET || 'qa-test'),
    CORS_ORIGIN:choose({},['QA_CORS_ORIGIN'],api.CORS_ORIGIN || 'http://127.0.0.1:5173'),
    PORT:qaPort,
  };
  // Safety: a real storage service requires explicit disposable-bucket acknowledgement.
  if (apiConfig.SUPABASE_URL!=='https://storage.invalid' && root.QA_STORAGE_TEST_BUCKET_ACK!=='I_VERIFIED_DISPOSABLE_BUCKET') {
    throw new Error('QA Supabase configured but QA_STORAGE_TEST_BUCKET_ACK is missing; refuse to use a real bucket');
  }
  const k6Url=root.K6_BASE_URL || (root.QA_API_PORT ? localApi : k6.K6_BASE_URL || localApi);
  safeOrigin(k6Url,false);
  const k6Config={K6_EXECUTION:raw('K6_EXECUTION',k6,'docker'),K6_DOCKER_IMAGE:raw('K6_DOCKER_IMAGE',k6,'grafana/k6:latest'),
    K6_BASE_URL:k6Url,K6_LOCAL_QA_ACK:raw('K6_LOCAL_QA_ACK',k6,'I_OWN_THIS_DISPOSABLE_QA_STACK'),
    PORT:qaPort};
  if (k6Config.K6_EXECUTION!=='docker' && k6Config.K6_EXECUTION!=='native') throw new Error('K6_EXECUTION must be docker/native');
  const browserFlag=raw('LHCI_CHROME_NO_SANDBOX',browser,'0');
  if (browserFlag!=='0' && browserFlag!=='1') throw new Error('LHCI_CHROME_NO_SANDBOX must be 0 or 1');
  const storageConfig={
    WEB_BASE_URL:choose(storage,['QA_STORAGE_WEB_BASE_URL'],'http://127.0.0.1:5173'),
    API_BASE_URL:choose(storage,['QA_STORAGE_API_BASE_URL'],localApi),
    OWNER_EMAIL:choose(storage,['QA_STORAGE_OWNER_EMAIL','QA_OWNER_EMAIL','OWNER_EMAIL']),
    OWNER_PASSWORD:choose(storage,['QA_STORAGE_OWNER_PASSWORD','QA_OWNER_PASSWORD','OWNER_PASSWORD']),
    // Explicit authorization comes only from the root .env (not an older sample file).
    QA_STORAGE_E2E_ACK:root.QA_STORAGE_E2E_ACK || '',
    QA_STORAGE_TEST_BUCKET_ACK:root.QA_STORAGE_TEST_BUCKET_ACK || '',
  };
  safeOrigin(storageConfig.WEB_BASE_URL,false); safeOrigin(storageConfig.API_BASE_URL,false);
  const webConfig={
    VITE_API_URL:choose(web,['QA_VITE_API_URL','QA_LOCAL_WEB_API_URL'],localApi),
    VITE_SUPABASE_ANON_KEY:choose(web,['QA_VITE_SUPABASE_ANON_KEY','VITE_SUPABASE_ANON_KEY']),
  };
  safeOrigin(webConfig.VITE_API_URL,false);
  const all=[
    ['vdr-qa-starter/.env',uiConfig,'dotenv'],
    ['virtual-data-room-main/apps/api/test/.env.test',apiConfig,'shell'],
    ['.env.k6',k6Config,'make'],['.env.browser',{LHCI_CHROME_NO_SANDBOX:browserFlag},'make'],
    ['vdr-qa-starter/.env.storage',storageConfig,'dotenv'],
    ['virtual-data-room-main/apps/web/.env.local',webConfig,'dotenv'],
  ];
  // Validate all serializations before touching any files.
  for (const [,obj,fmt] of all) for (const value of Object.values(obj)) (fmt==='shell'?bashValue:fmt==='make'?makeValue:dotenvValue)(String(value));
  for (const [name,obj,fmt] of all) write(name,obj,fmt);
  console.log(`[env-sync] Generated ${all.length} QA environment files (0600); root .env ${existsSync(join(ROOT,'.env'))?'loaded':'absent'}.`);
  if (!ownerEmail || !ownerPassword) console.log('[env-sync] OWNER_EMAIL/OWNER_PASSWORD missing. Set them once in root .env to enable read-only UI/API tests.');
  if (!storageConfig.QA_STORAGE_E2E_ACK || !storageConfig.QA_STORAGE_TEST_BUCKET_ACK) console.log('[env-sync] Real Storage E2E remains disabled (explicit disposable-environment acknowledgements required).');
  console.log('[env-sync] Test database is isolated at local vdr_qa_test; root production DB URLs are ignored.');
}
if (process.argv[1] && resolve(process.argv[1])===fileURLToPath(import.meta.url)) {
  try {run();} catch(e) {console.error('[env-sync] '+e.message);process.exitCode=2;}
}
export {parseEnv,localPg};
